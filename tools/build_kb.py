# Departments renamed to the names a patient would recognise at a hospital desk
DEPT = {"أمراض الصدر": "صدرية", "قلب وأوعية دموية": "قلب", "روماتيزم": "روماتيزم ومناعة",
        "نفسية": "طب نفسي", "أعصاب": "مخ وأعصاب"}

def canon(s):
    v = SYN.get(s, s)
    return v if isinstance(v, list) else [v]

diseases, before, dup_removed = [], set(), 0
for i, d in enumerate(raw):
    syms = []
    for s in d["symptoms"]:
        before.add(s)
        for c in canon(s):
            if c in syms:
                dup_removed += 1
            else:
                syms.append(c)
    diseases.append({"id": i + 1, "name": d["name"].strip(),
                     "department": DEPT.get(d["department"], d["department"]),
                     "symptoms": syms})

after = collections.Counter(s for d in diseases for s in d["symptoms"])
unused = [k for k in SYN if k not in before]
report = {"diseases": len(diseases), "symptoms_before": len(before), "symptoms_after": len(after),
          "duplicates_removed_within_disease": dup_removed, "unused_synonym_keys": unused,
          "departments": collections.Counter(d["department"] for d in diseases)}
json.dump(report, open(f"{out}/kb-report.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)

with open(f"{out}/kb.js", "w", encoding="utf-8") as f:
    f.write("// IDOS knowledge base — generated by tools/build_kb.py from the original diseases.json.\n")
    f.write("// Symptom names are canonicalised (synonyms merged) so the matcher compares concepts, not spellings.\n")
    f.write("export const DISEASES = ")
    json.dump(diseases, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
    f.write("// Alternative spellings found in the source data -> canonical symptom(s).\n")
    f.write("export const ALIASES = ")
    json.dump({k: canon(k) for k in SYN}, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print(json.dumps(report, ensure_ascii=False, indent=1))
